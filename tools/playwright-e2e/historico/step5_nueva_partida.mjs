import { chromium } from 'playwright';

const browser = await chromium.launch();
const page = await browser.newPage();
page.on('pageerror', err => console.log('[pageerror]', err.message));
page.on('requestfailed', req => console.log('[requestfailed]', req.url(), req.failure()?.errorText));
await page.goto('http://localhost:5173/solitario/mundo/helek-sirik/personaje/char-gorhorn');
await page.waitForTimeout(1000);
await page.getByText('Novato', { exact: true }).first().click();
await page.waitForTimeout(500);
await page.screenshot({ path: 'screenshots/step5_before_click.png', fullPage: true });
const buttons = await page.getByRole('button').allInnerTexts();
console.log('BOTONES DISPONIBLES:', JSON.stringify(buttons));
await page.locator('button', { hasText: 'Nueva partida' }).click();
await page.waitForTimeout(3000);
await page.screenshot({ path: 'screenshots/step5_nueva_partida.png', fullPage: true });
const bodyText = await page.locator('body').innerText();
console.log('BODY TEXT:\n', bodyText.slice(0, 4000));
console.log('URL:', page.url());
await browser.close();
console.log('OK');
